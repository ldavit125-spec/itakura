/** 한글 문자열을 가타카나로 자동 번역 */
function autoTransliterateHangul(text: string): string {
  let result = text;
  for (const [regex, replacement] of WORD_REPLACEMENTS) {
    result = result.replace(regex, replacement);
  }
  // 남아 있는 한글 음절 자동 변환
  result = result.replace(/[\uac00-\ud7a3]/g, (ch) => hangulSyllableToKatakana(ch));
  return result;
}

/**
  언어별 명칭/텍스트 표시 공통 함수
 - locale이 "ja"이고 ja 값이 존재(non-empty string)하면 ja 반환
 - ja 값이 없을 경우 사전/규칙 및 한글 음역 자동 매핑을 적용하여 일본어로 반환
 - 그 외의 경우 ko (fallback) 반환
*/
export function localizedName({ locale, ko, ja }: LocalizedNameOptions): string {
  if (locale === "ja") {
    if (ja && ja.trim().length > 0) {
      return ja.trim();
    }
    if (ko && DEFAULT_JA_FALLBACKS[ko.trim()]) {
      return DEFAULT_JA_FALLBACKS[ko.trim()];
    }
    if (ko && ko.trim().length > 0) {
      return autoTransliterateHangul(ko.trim());
    }
  }
  return ko ?? "";
}
